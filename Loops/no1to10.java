package DSA.Loops;

public class no1to10 {
    public static void main(String[] args) {
        for(int i=0 ; i<=10 ; i++){
            System.out.println("The Number Is :" + i);
        }
        int j = 1 ;
        while (j <= 10) {
            System.out.println(j);
            j++;
        }
    }
}
